# Regenerates the SPIR-V for the Vulkan renderer (compose.comp.inc), so the
# core builds without a shader compiler.  Only needed after compose.comp
# changes.
#
# glslc is taken from, in order: $GLSLC; the Android NDK's shader-tools
# ($NDK, or the newest NDK under the Android SDK); glslc on the PATH.
set -e
DIR=$(cd "$(dirname "$0")" && pwd)

if [ -z "$GLSLC" ]; then
    SDK=${ANDROID_HOME:-${ANDROID_SDK_ROOT:-${LOCALAPPDATA:+$LOCALAPPDATA/Android/Sdk}}}
    NDK=${NDK:-$(ls -d "$SDK"/ndk/* 2>/dev/null | tail -1)}
    [ -n "$NDK" ] && NDK=$(cygpath -u "$NDK" 2>/dev/null || echo "$NDK")
    [ -n "$NDK" ] && GLSLC=$(ls "$NDK"/shader-tools/*/glslc* 2>/dev/null | head -1)
    [ -z "$GLSLC" ] && GLSLC=$(command -v glslc || true)
fi
if [ -z "$GLSLC" ] || [ ! -x "$GLSLC" ]; then
    echo "glslc not found: set GLSLC=/path/to/glslc or NDK=/path/to/android-ndk" >&2
    exit 1
fi

OUT=$(mktemp)
{
    echo "// Generated by shaders/build.sh from compose.comp with $("$GLSLC" --version | head -1)"
    "$GLSLC" -fshader-stage=compute --target-env=vulkan1.0 -O -mfmt=c -o - "$DIR/compose.comp"
} > "$OUT"
mv "$OUT" "$DIR/compose.comp.inc"
echo "wrote $DIR/compose.comp.inc"
